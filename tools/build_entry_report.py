"""Regenerate public API validation report and timing CSV from raw GPU evidence."""
import argparse,csv,io,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];E=ROOT/'experiments/20261024-unified-entry'
def load(name):return json.loads((E/'results'/name).read_text())
def generate():
 checks=load('validation.json');mem=load('memcheck.json');bench=load('benchmark.json')
 assert len(checks)==90 and all(x['pass_exact'] for x in checks)
 assert len(mem)==46 and all(x['pass_exact'] for x in mem)
 assert 'ERROR SUMMARY: 0 errors' in (E/'logs/memcheck.log').read_text()
 assert len(bench)==8
 lines=['<!-- Generated by tools/build_entry_report.py; do not edit. -->','# 统一公共入口验证与设备计时','',
        '本轮验证src/gdn_prefill的prepare/run封装；只使用GPU6，没有启动模型服务。代码SHA256见[evidence/runtime_source_manifest.json](evidence/runtime_source_manifest.json)，环境见[evidence/environment.json](evidence/environment.json)。',
        '', '## 结果','',
        '- 90项差分/graph检查全部通过：84项stable路径输出、最终状态及请求checkpoint逐位对照，以及6项实验CP checkpoint相对原CP前缀状态的动态检查。',
        '- 46项memcheck子集检查全部通过，Compute Sanitizer 0 errors。启用stream-ordered race tracking、32-byte padding；关闭API查询返回码报告，不宣称执行了完整racecheck。',
        '- 覆盖两个geometry、N1/2/3/4/8、空序列、非整块尾部、initial_state=None、多checkpoint完整回退、稀疏slot、mixed CP、metadata更新及关闭checkpoint。',
        '- 这是合成数据的封装差分测试，不是新服务部署、长期soak或模型质量测试。near-one的既有CP/non-CP失败见[CP边界实验](../20261024-gdn-cp-checkpoint-fix/README.md)，没有被本轮覆盖或取消。',
        '', '## 公共入口计时','',
        '所有方法走新公共入口，11轮随机交错、每轮40次CUDA Graph replay。数字为每轮均值的中位数ms，包含GPU侧状态写出/gather/scatter，不含CPU prepare、校验或调度时间。固定seed=20261024、普通linear gate，计时前后检查全部输出/状态；原始样本与顺序见[benchmark.json](results/benchmark.json)。',
        '', '| geometry | 输入tokens | checkpoint targets | original dense fallback | full-V | V2 | auto | auto选择 | experimental CP |',
        '|---|---|---|---:|---:|---:|---:|---|---:|']
 csvrows=[]
 for r in bench:
  t={k:v['median_ms'] for k,v in r['timing'].items()}
  for stage in ['checks','post_timing']:
   assert all(v['close'] for c in r[stage].values() for v in c.values())
  lines.append(f"| Hq{r['hq']}/Hv{r['hv']} | {r['lengths']} | {r['targets']} | {t['original']:.4f} | {t['full']:.4f} | {t['v2']:.4f} | {t['auto']:.4f} | {r['auto']} | {t['cp_checkpoint']:.4f} |")
  for name,v in r['timing'].items():csvrows.append(dict(hq=r['hq'],hv=r['hv'],lengths=str(r['lengths']),targets=str(r['targets']),backend=name,auto_choice=r['auto'],median_ms=v['median_ms']))
 lines+=['', 'original列包含dense64计算和向同一公开输出契约scatter的开销，与旧实验“原始算子”计时不是同一个范围。experimental CP仍未通过全部near-one回归，速度不构成启用许可。auto没有把它作为候选；多序列full/V2选择与已测shape一致。',
         '', '## 重现命令','', '```bash',
         'CUDA_VISIBLE_DEVICES=6 PYTHONPATH=src python benchmarks/validate_entry.py --out validation.json',
         'CUDA_VISIBLE_DEVICES=6 PYTHONPATH=src /usr/local/cuda/bin/compute-sanitizer --tool memcheck --report-api-errors no --track-stream-ordered-races all --padding 32 --error-exitcode 99 python benchmarks/validate_entry.py --memcheck --out memcheck.json',
         'CUDA_VISIBLE_DEVICES=6 PYTHONPATH=src python benchmarks/benchmark_entry.py --out benchmark.json',
         '```','', '在仓库根目录、匹配环境中执行，并确保GPU6空闲且有授权。本次Python为/opt/sglang/bin/python。测试完成后GPU6/7显存均归零，见[gpu_after.csv](evidence/gpu_after.csv)。',
         '', '[差分原始结果](results/validation.json) · [memcheck原始结果](results/memcheck.json) · [memcheck日志](logs/memcheck.log) · [CSV](../../data/entry_benchmark.csv) · [入口文档](../../docs/unified-entry.md)','']
 stream=io.StringIO();writer=csv.DictWriter(stream,fieldnames=list(csvrows[0]),lineterminator='\n');writer.writeheader();writer.writerows(csvrows)
 return {E/'README.md':'\n'.join(lines),ROOT/'data/entry_benchmark.csv':stream.getvalue()}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 for path,text in generate().items():
  if args.check:assert path.read_text()==text,f'Stale report: {path}'
  else:path.write_text(text)
 print('Public-entry report verified: 90 checks, 46 memcheck, 8 timing cases')
if __name__=='__main__':main()
