"""Generate same-version cross-geometry tables and CP boundary audit from raw results."""
import argparse,csv,io,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def read(path):return json.loads((ROOT/path).read_text())
def csv_text(rows):
 s=io.StringIO();w=csv.DictWriter(s,fieldnames=list(rows[0]),lineterminator='\n');w.writeheader();w.writerows(rows);return s.getvalue()
def generate():
 unified=read('experiments/20261024-gdn-unified-checkpoint/results/benchmark.json')
 cp=read('experiments/20261024-gdn-cp-checkpoint-fix/results/benchmark.json')
 audit=read('experiments/20261024-gdn-cp-checkpoint-fix/results/boundary_audit.json')
 rows=[]
 for r in unified:
  for name,timing in r['timing'].items():
   rows.append(dict(model=r['model'],lengths=str(r['lengths']),targets=str(r['targets']),method=name,median_ms=timing['median_ms']))
 candidate=[]
 for r in cp:
  for name,timing in r['times'].items():candidate.append(dict(model=r['model'],lengths=str(r['lengths']),targets=str(r['targets']),method=name,median_ms=timing['median_ms'],native_chunk=r['native_chunk'],old_chunk=r['old_chunk']))
 boundaries=[dict(model=r['model'],gate=r['gate'],target=r['target'],cp_chunk=r['cp_chunk'],old_error=r['old_vs_cp_prefix']['max_abs'],new_error=r['native_vs_cp_prefix']['max_abs'],new_exact=r['native_vs_cp_prefix']['exact']) for r in audit]
 files={'unified_kernel_comparison.csv':csv_text(rows),'native_cp_comparison.csv':csv_text(candidate),'cp_boundary_errors.csv':csv_text(boundaries)}
 doc=['<!-- Generated by tools/build_unified_tables.py; do not edit. -->','# 跨 geometry 同版本对比与 CP checkpoint 修复','',
      '以下均为 H20、FlashInfer 0.6.18 的合成 CUDA Graph 设备时间（ms），不是完整模型或服务延迟。122B 表示 Hq4/Hv16，35B 表示 Hq16/Hv32；不混入原 122B 开发版报告。',
      '原始逐轮 samples、随机执行顺序、正确性结果和失败项见对应实验目录。API 重构另有验证，不把这些旧函数计时冒充新公共入口的完整开销。','',
      '## native CP 与选定 checkpoint 的同条件比较','',
      '| geometry | 输入 | 目标 | full-V | V2 | 旧 CP 提取 | native CP | mixed native CP |','|---|---|---|---:|---:|---:|---:|---:|']
 for r in cp:
  t={k:v['median_ms'] for k,v in r['times'].items()};mixed=f"{t['mixed_native']:.4f}" if 'mixed_native' in t else '—'
  doc.append(f"| {r['model']} | {r['lengths']} | {r['targets']} | {t['full_selected']:.4f} | {t['v2_selected']:.4f} | {t['old_fixup_extraction']:.4f} | {t['native_cp_selected']:.4f} | {mixed} |")
 doc+=['','旧 CP 提取有边界缺陷，只作诊断对照；native CP 固定 chunk=2048，旧整批提取使用 gcd(2048,targets)。普通 gate 计时前通过容差检查，near-one 数值回归仍失败，native CP checkpoint 不进入 stable 自动分流。','',
       '## CP 前缀状态对照','',
       '| geometry | gate | checkpoint token | 旧提取最大误差 | 新写出最大误差 | 逐位一致 |','|---|---|---:|---:|---:|---|']
 for r in boundaries:doc.append(f"| {r['model']} | {r['gate']} | {r['target']} | {r['old_error']:.8f} | {r['new_error']:.8f} | {r['new_exact']} |")
 doc+=['','该表参考为同条件原版 CP 跑到指定前缀的最终状态，不是 non-CP 或独立高精度参考。',
       '', '[统一 checkpoint 原实验](../experiments/20261024-gdn-unified-checkpoint/README.md) · [CP 修复完整报告](../experiments/20261024-gdn-cp-checkpoint-fix/README.md)',
       '', '[全方法 CSV](../data/unified_kernel_comparison.csv) · [CP 候选全方法 CSV](../data/native_cp_comparison.csv) · [边界误差 CSV](../data/cp_boundary_errors.csv)','']
 return {**{ROOT/'data'/k:v for k,v in files.items()},ROOT/'docs/unified-tables.md':'\n'.join(doc)}
def main():
 p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
 for path,data in generate().items():
  if args.check:assert path.read_text()==data,f'Stale: {path}'
  else:path.write_text(data)
 print('Cross-geometry tables regenerated/verified from raw JSON')
if __name__=='__main__':main()
